#!/bin/bash
set -uo pipefail

# Key Manager step 1: red key, RSA pairs, PPK0 hash, efuse_keys.txt. No images.
# Keys are never overwritten. New set = clear the tree first. See README.md.

# Lives in files/ (internal: ./key_manager.sh --gen-keys <dir> runs it); every path
# below is relative to scripts/secure_boot/, one level up, exactly as before the move.
SCRIPT_DIR=$(dirname "$(dirname "$(readlink -f "$0")")")
cd "$SCRIPT_DIR" || exit 1

FILES_DIR=files
LOG_ROOT=${FILES_DIR}/logs
# files/ absolute - step bodies cd into it and name paths inside it in messages.
BASE_DIR="${SCRIPT_DIR}/${FILES_DIR}" # files/, absolute

# Same default files/_sign_secure_boot.sh uses - they must agree. Git-ignored, and the
# same path the step bodies fall back to. Must survive a git clean.
KEY_ROOT="${BASE_DIR}/secure_boot_keys"
# empty = the blank-board default in step 3; a value here is used
# instead, for a board that already holds some of those fuses
EFUSE_WRITE=
VERBOSE=0

# shellcheck source=files/_steplib.sh
. "${FILES_DIR}/_steplib.sh"

# ============================== Steps =======================================
# Subshells (_steplib.sh): exit and cd stay local. Report via sb_pass/bad/warn/die.

# ---------------------------------------------------------------- 1. the keys
# Layout and backup rules: README.md. Existing files kept, never overwritten.
sb_step_gen_keys() {
    cd "$FILES_DIR" || exit 1

    # SB_KEY_ROOT absolute when --keys was given. Shadows the wrapper's copy - safe,
    # steps are subshells.
    KEY_ROOT=${SB_KEY_ROOT:-keys}
    SECRET_KEY_FILE=${KEY_ROOT}/secret_key.txt
    RSA_DIR=${KEY_ROOT}/RSA
    # bootgen writes the .nky files here; created now so the layout exists up front
    AES_DIR=${KEY_ROOT}/AES
    # must match the pskfile/sskfile paths in bifs/bootgen_secured.bif
    RSA_KEYS="psk1_rsa.pem ssk1_rsa.pem"

    # the key files live inside keys/, so the tree has to exist before writing any
    mkdir -p "$RSA_DIR" "$AES_DIR"

    # Complete or empty, never in between: a regenerated key beside surviving ones is
    # a set that boots on no board. Duplicated from preflight, next to the damage.
    n_have=0
    for f in "$SECRET_KEY_FILE" "$RSA_DIR/psk1_rsa.pem" "$RSA_DIR/ssk1_rsa.pem"; do
        [ -f "$f" ] && n_have=$((n_have + 1))
    done
    if [ "$n_have" -ne 0 ] && [ "$n_have" -ne 3 ]; then
        echo "ERROR: partial key set in ${KEY_ROOT} - ${n_have} of 3 files present." >&2
        echo "       These three keys are one set and this step will not complete one" >&2
        echo "       half of it. Restore the missing file from the backup of that whole" >&2
        echo "       tree, or move the tree aside to start a new set - never for a" >&2
        echo "       board family whose PPK0 hash is already burned." >&2
        exit 1
    fi

    # AES-256 red key: 64 hex chars, same format bootgen uses in .nky files
    if [ -f "$SECRET_KEY_FILE" ]; then
        echo "keep : $SECRET_KEY_FILE"
    else
        openssl rand -hex 32 | tr 'a-f' 'A-F' | sed 's/$/;/' > "$SECRET_KEY_FILE"
        chmod 600 "$SECRET_KEY_FILE"
        echo "new  : $SECRET_KEY_FILE (AES-256 red key)"
    fi

    for key in $RSA_KEYS; do
        if [ -f "$RSA_DIR/$key" ]; then
            echo "keep : $RSA_DIR/$key"
            continue
        fi
        openssl genrsa -out "$RSA_DIR/$key" 4096
        chmod 600 "$RSA_DIR/$key"
        echo "new  : $RSA_DIR/$key (RSA-4096)"
    done

    echo
    echo "Keep the whole $KEY_ROOT/ tree safe and do NOT commit it."
}

# ------------------------------------------------------------ 2. the PPK0 hash
sb_step_ppk0_hash() {
    cd "$FILES_DIR" || exit 1

    KEY_ROOT=${SB_KEY_ROOT:-keys}
    PSK_FILE=${KEY_ROOT}/RSA/psk1_rsa.pem
    PPK_HASH_FILE=${KEY_ROOT}/ppk0_hash.txt
    # BIF naming the PSK only. Generated per run: a committed one would hardcode a
    # keys/ path that --keys breaks.
    PPK_BIF=

    [ -f "$PSK_FILE" ] || sb_die "not found: $PSK_FILE (step 1 should have made it)"

    if ! command -v bootgen > /dev/null 2>&1; then
        echo "ERROR: bootgen not found in PATH - cannot derive the PPK0 hash." >&2
        echo "Source the Vitis/PetaLinux settings first (e.g. source <vitis>/settings64.sh)." >&2
        exit 1
    fi

    # Absolute, because bootgen resolves BIF paths against its own CWD and the temp
    # BIF does not sit in this directory.
    PSK_ABS=$(readlink -f "$PSK_FILE")

    WORK=$(mktemp -d) || sb_die "cannot create a temp directory"
    trap 'rm -rf "$WORK"' EXIT
    PPK_BIF="${WORK}/ppk_gen.bif"
    {
        printf '// Generated by gen_keys.sh. No partitions on purpose: this BIF\n'
        printf '// exists only to name a key bootgen can be asked to hash.\n'
        printf 'digestgen_psk0_bif:\n{\n'
        printf '  pskfile        = %s\n' "$PSK_ABS"
        printf '}\n'
    } > "$PPK_BIF" || sb_die "cannot write $PPK_BIF"

    # bootgen, not 'openssl dgst': the hash covers bootgen's PPK struct byte order,
    # not the PEM/DER encoding.
    mkdir -p "$KEY_ROOT" || sb_die "cannot create $KEY_ROOT"
    rm -f "$PPK_HASH_FILE"

    if ! BOOTGEN_OUT=$(bootgen -arch versal -image "$PPK_BIF" \
        -efuseppkbits "$PPK_HASH_FILE" 2>&1); then
        echo "ERROR: bootgen failed to generate the PPK0 hash:" >&2
        printf '%s\n' "$BOOTGEN_OUT" >&2
        exit 1
    fi

    # bootgen writes the hash CRLF-terminated, so grep the hex out rather than reading
    # the line as-is.
    PPK0_HASH=$(grep -oE '[0-9a-fA-F]{64}' "$PPK_HASH_FILE" | head -1 | tr 'a-f' 'A-F')
    if [ -z "$PPK0_HASH" ]; then
        echo "ERROR: no 64-hex PPK0 hash in bootgen output." >&2
        echo "bootgen said:" >&2
        printf '%s\n' "$BOOTGEN_OUT" >&2
        exit 1
    fi

    # Rewritten normalised, so every reader downstream sees one spelling rather than
    # whichever case and line ending bootgen happened to use.
    printf '%s\n' "$PPK0_HASH" > "$PPK_HASH_FILE"

    echo "new  : ${PPK_HASH_FILE} (derived from $(basename "$PSK_FILE"))"
    echo "PPK0_HASH = ${PPK0_HASH}"
    echo
    echo "Public value. Record it in the board-family register: after a burn it is the"
    echo "only field a read-back can be checked against - the AES key is write-only."
}

# ----------------------------------------------------------- 3. the key file
sb_step_efuse_keyfile() {
    cd "$FILES_DIR" || exit 1

    FORMAT=mango-efuse-keys/1

    KEY_ROOT=${SB_KEY_ROOT:-keys}
    SECRET_KEY_FILE=${KEY_ROOT}/secret_key.txt
    PPK_HASH_FILE=${KEY_ROOT}/ppk0_hash.txt

    OUT=${1:-${KEY_ROOT}/efuse_keys.txt}

    # Which fields this burn is meant to write. Same variable and same default the rest
    # of the flow uses, because the list has to mean one thing across it.
    #
    # One burn, three stages. The provisioning firmware issues three separate
    # XNvm_EfuseWrite calls - values, then policy, then locks - and stops at the
    # first that fails (provision_endpoint.cpp: stageValues && stagePolicy &&
    # stageLocks). xilnvm orders the same way inside one request - keys, hashes and
    # IVs first, XNvm_EfuseWriteSecCtrl last - so a lock can never land before its
    # subject, and arming PPK0_WR_LK alongside PPK0_HASH in one request is safe.
    #
    # The default is the blank-board burn for A-HWRoT with red-key encryption: the red
    # key, the PPK0 hash, the two IVs, and the one lock that seals the hash. The images
    # this flow signs are encrypted with keysrc = efuse_red_key throughout, so AES_KEY
    # belongs in the same burn - a part whose AES row is empty opens none of them.
    #
    # Two fuses a blank-board burn could also take are deliberately NOT in it:
    #
    #   DEC_ONLY   REFUSED by the checks below. It puts the part in S-HWRoT, which
    #              decrypts only with a PUF KEK, and every BIF here is keysrc =
    #              efuse_red_key. LP R.2 was lost this way on 2026-08-05 (ROM 0x308 on
    #              every slot, then 0x30F).
    #   AES_WR_LK  settable, but not armed by default: sealing the AES row gives up the
    #              option of ever loading it with a PUF-wrapped black key, which is the
    #              only path to S-HWRoT. Arm it with --efuse-write once a part's key burn
    #              is confirmed and that path is not wanted.
    DEFAULT_WRITE="AES_KEY PPK0_HASH METAHEADER_IV PLM_IV PPK0_WR_LK"
    ARMED=${SB_EFUSE_WRITE:-}
    [ -n "$ARMED" ] || ARMED=$DEFAULT_WRITE

    # A policy fuse has no width: its slot carries the literal 1, which the firmware
    # rechecks as a countersignature over the arm mask (key_blob.hpp refuses an armed
    # policy slot that does not say 1 - KeyBlobStatus::PolicyValue).
    POLICY_ON=1

    # The policy fuses this flow can set a value for. Wider than the default arm list on
    # purpose: AES_WR_LK is settable so --efuse-write can arm it on a part whose key burn
    # is already confirmed. PPK1/PPK2 and the user keys are not settable at all - those
    # slots stay open so the RSA key set can be rotated and a botched PPK0_HASH burn still
    # has a recovery path.
    SETTABLE_POLICY="AES_WR_LK PPK0_WR_LK"

    # Refused, not merely unset - these two are the ones that end a board.
    #
    #   DEC_ONLY    S-HWRoT decryption requires a PUF KEK (AMD's Cumulative Secure Boot
    #               Operations table). This flow is efuse_red_key throughout, so after
    #               the burn the ROM refuses every image it can build: 0x308 per
    #               candidate, then 0x30F when the golden fallback exhausts the range.
    #               LP R.2 was lost this way on 2026-08-05. It needs the whole PUF/black
    #               key design first - PUF registration, BLACK_IV, keysrc =
    #               efuse_black_key - not a fuse to flip.
    #   AES_CRC_LK  The AES row is write-only, so its CRC check is the only channel that
    #               can ever say anything about the stored key. Locking it seals the
    #               check, not the key, and gives up verification on this board and on
    #               any RMA return.
    REFUSED_POLICY="DEC_ONLY AES_CRC_LK"

    # Membership in a space-separated list. Defined here because the checks below and
    # the writer at the end both ask.
    is_armed() { case " $ARMED " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
    is_settable_policy() { case " $SETTABLE_POLICY " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
    is_refused_policy() { case " $REFUSED_POLICY " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

    # shellcheck source=../_efuse_iv.sh
    . ./_efuse_iv.sh

    fail=0

    [ -f "$SECRET_KEY_FILE" ] || sb_die "not found: $SECRET_KEY_FILE (step 1 should have made it)"
    [ -f "$PPK_HASH_FILE" ] || sb_die "not found: $PPK_HASH_FILE (step 2 should have made it)"

    # first hex run of the wanted length, uppercased: the key file carries a trailing
    # ';' and bootgen's hash file a CR, so neither can be read as a whole line
    hex() { grep -oE "[0-9a-fA-F]{$2}" "$1" | head -1 | tr 'a-f' 'A-F'; }

    AES_KEY=$(hex "$SECRET_KEY_FILE" 64)
    PPK0_HASH=$(hex "$PPK_HASH_FILE" 64)
    METAHEADER_IV=$SB_METAHEADER_IV0
    PLM_IV=$SB_PLM_IV0

    echo "sources :"
    printf '  %-14s %s\n' AES_KEY "$SECRET_KEY_FILE"
    printf '  %-14s %s\n' PPK0_HASH "$PPK_HASH_FILE"
    printf '  %-14s %s\n' METAHEADER_IV "${BASE_DIR}/_efuse_iv.sh"
    printf '  %-14s %s\n' PLM_IV "${BASE_DIR}/_efuse_iv.sh"
    for p in $SETTABLE_POLICY; do
        printf '  %-14s %s\n' "$p" '1-bit policy fuse - no source to read'
    done
    echo
    printf 'armed   : %s\n' "$ARMED"
    echo

    # ------------------------------------------------------------------- checks
    # A file short one value is worse than none: it reads as a complete OTP record.
    echo "[1] the values this flow sets"
    check() {
        local field=$1 value=$2 want=$3 src=$4
        if [ -z "$value" ]; then
            sb_bad "$field: no ${want}-hex value in $src"
        elif [ "${#value}" -ne "$want" ]; then
            sb_bad "$field: ${#value} hex chars in $src, expected $want"
        elif printf '%s' "$value" | grep -qE '^0+$'; then
            sb_bad "$field: all zeros in $src"
        else
            sb_pass "$field = $value"
        fi
    }
    check AES_KEY "$AES_KEY" 64 "$SECRET_KEY_FILE"
    check PPK0_HASH "$PPK0_HASH" 64 "$PPK_HASH_FILE"
    check METAHEADER_IV "$METAHEADER_IV" 24 _efuse_iv.sh
    check PLM_IV "$PLM_IV" 24 _efuse_iv.sh

    # Nothing to read for these - the whole value is the 1 the format demands. Checked
    # once, then listed per fuse, because this is the list an operator reads before an
    # irreversible burn.
    if [ "$POLICY_ON" != 1 ]; then
        sb_bad "a policy slot must say 1, not '$POLICY_ON' - the firmware refuses the blob"
    else
        for p in $SETTABLE_POLICY; do sb_pass "$p = $POLICY_ON (policy bit)"; done
    fi

    # IV reuse under one key loses AES-GCM's integrity guarantee. files/_sign_secure_boot.sh
    # checks the same thing on the image side; this catches it before anything is built.
    if [ -n "$METAHEADER_IV" ] && [ "$METAHEADER_IV" = "$PLM_IV" ]; then
        sb_bad "METAHEADER_IV and PLM_IV are identical - IV reuse under the same key"
    fi
    echo

    # ------------------------------------------------------------- armed vs values
    # The injector refuses this too; catching it here beats hearing it after handover.
    echo "[2] every armed field has a value"
    value_of() {
        case "$1" in
            AES_KEY) printf '%s' "$AES_KEY" ;;
            PPK0_HASH) printf '%s' "$PPK0_HASH" ;;
            METAHEADER_IV) printf '%s' "$METAHEADER_IV" ;;
            PLM_IV) printf '%s' "$PLM_IV" ;;
            *)
                # a policy fuse this flow can set carries the literal 1; anything
                # else - PPK1/2 and user-key locks included - has no value here
                if is_settable_policy "$1"; then printf '%s' "$POLICY_ON"; else printf -- '-'; fi
                ;;
        esac
    }
    for f in $ARMED; do
        # [3] owns the refused ones, with the reason. Reporting "no value for it" here
        # would send the reader looking for a source file for a fuse that must not be
        # armed at all.
        if is_refused_policy "$f"; then
            continue
        elif [ "$(value_of "$f")" = '-' ]; then
            sb_bad "$f is armed and this flow sets no value for it"
            printf '         settable: AES_KEY PPK0_HASH METAHEADER_IV PLM_IV %s\n' "$SETTABLE_POLICY"
        else
            sb_pass "$f is armed and carries a value"
        fi
    done
    echo

    # ------------------------------------------------------ policy this flow refuses
    # Separate from [2] because the reason is a decision, not a missing value: the
    # message has to say why rather than send the operator looking for a source file.
    echo "[3] policy this flow refuses to arm"
    for f in $REFUSED_POLICY; do
        if ! is_armed "$f"; then
            sb_pass "$f is not armed"
            continue
        fi
        sb_bad "$f is armed - this flow refuses it"
        case "$f" in
            DEC_ONLY)
                printf '         DEC_ONLY puts the part in S-HWRoT, which decrypts ONLY with a PUF\n'
                printf '         KEK (efuse_black_key). Every BIF in this flow says keysrc =\n'
                printf '         efuse_red_key, so the ROM would refuse every image it builds\n'
                printf '         (0x308) and the golden fallback would then exhaust the address\n'
                printf '         range (0x30F). Nothing boots, and eFUSE is one-time: LP R.2 was\n'
                printf '         lost this way on 2026-08-05.\n'
                printf '         Encrypted boot IS used here - it is just not mandated by the ROM.\n'
                printf '         Arming it needs the PUF/black-key design first: PUF registration,\n'
                printf '         BLACK_IV, and keysrc = efuse_black_key through every BIF.\n'
                ;;
            AES_CRC_LK)
                printf '         The AES key is write-only in silicon, so its CRC check is the only\n'
                printf '         way to verify the burn landed. Locking it removes the per-board QC\n'
                printf '         signal and seals the check, not the key.\n'
                ;;
        esac
    done
    echo

    # A lock over an empty slot seals it, and the field can then never be written.
    #
    # A warning and not a failure, because this script cannot see the board: arming
    # only the locks is exactly right for a follow-up burn on a part whose values are
    # already in. The firmware is the one that can tell, and it refuses the real
    # mistake - "the field this locks is neither armed here nor already burned"
    # (provision_endpoint.cpp whyNot). This only says which case the operator is in.
    echo "[4] every armed lock has a subject"
    lock_subject() {
        case "$1" in
            AES_WR_LK) printf 'AES_KEY' ;;
            PPK0_WR_LK) printf 'PPK0_HASH' ;;
            PPK1_WR_LK) printf 'PPK1_HASH' ;;
            PPK2_WR_LK) printf 'PPK2_HASH' ;;
            USER_KEY0_WR_LK) printf 'USER_KEY0' ;;
            USER_KEY1_WR_LK) printf 'USER_KEY1' ;;
            *) printf -- '-' ;;
        esac
    }
    for f in $ARMED; do
        subject=$(lock_subject "$f")
        [ "$subject" = '-' ] && continue
        if is_armed "$subject"; then
            sb_pass "$f locks $subject, which this burn writes"
        else
            sb_warn "$f is armed but $subject is not - only correct if $subject"
            printf '         is ALREADY burned on the target board. Confirm it with a read-back\n'
            printf '         first: on a part where it is not, the firmware refuses the lock, and\n'
            printf '         a lock that lands over an empty slot is a board to scrap.\n'
        fi
    done
    echo

    if [ "$fail" -ne 0 ]; then
        echo "RESULT: FAIL - $OUT not written."
        exit 1
    fi

    # ------------------------------------------------------------------- write
    # Field order below IS burn order - values, policy, locks - the same order
    # fw_meta.py's EFUSE_FIELDS and key_blob.hpp's field bits use, and the order the
    # firmware's three write stages run in. Armed noted with a semicolon.
    # "not armed" spelled out rather than left as the absence of "armed": a policy slot
    # that carries 1 without being armed is the one line in this file a reader can take
    # for a burn that is about to happen.
    note() {
        if is_armed "$1"; then
            printf '   # armed; %s' "$2"
        else printf '   # not armed; %s' "$2"; fi
    }

    TMP=$(mktemp) || sb_die "cannot create a temp file"
    trap 'rm -f "$TMP"' EXIT

    {
        printf '# eFUSE values for this key set. GENERATED - do not edit by hand.\n'
        printf '%-9s = %s\n' FORMAT "$FORMAT"
        printf '%-9s = %s\n' GENERATED "$(date '+%Y-%m-%dT%H:%M:%S%:z')"
        printf '%-9s = %s\n' PROJECT "$(readlink -f "$KEY_ROOT")"
        printf '%-9s = %s\n' ARMED "$ARMED"
        printf '#\n'
        printf '# ARMED is what this burn writes. Every other field is listed so the file is\n'
        printf '# a complete record of the fuse set, and carries "-" - this format'"'"'s spelling\n'
        printf '# for "no value". Arming a "-" field is refused. A field that carries a value\n'
        printf '# without an "armed" note is not written by this burn.\n'
        printf '#\n'
        printf '# PPK0_HASH is not a stored key: it is derived from the PSK, and burning a\n'
        printf '# wrong one locks the board out for good.\n'
        printf '#\n'
        printf '# The order below is the burn order. The firmware writes it in three stages -\n'
        printf '# values, then policy, then locks - stopping at the first that fails, so a\n'
        printf '# lock can never land before the field it seals.\n'
        printf '#\n'
        printf '# A policy fuse has no width: its slot carries 1, which the firmware rechecks\n'
        printf '# against the arm mask. Two of them are REFUSED here, not merely unset:\n'
        printf '# DEC_ONLY, because S-HWRoT decrypts only with a PUF KEK while every BIF in\n'
        printf '# this flow is keysrc = efuse_red_key (LP R.2 was lost to it on 2026-08-05);\n'
        printf '# and AES_CRC_LK, because the AES row is write-only and its CRC check is the\n'
        printf '# only proof a burn landed. PPK0_WR_LK is the one lock armed by default.\n'
        printf '# AES_WR_LK carries a value but is left unarmed - sealing the AES row gives up\n'
        printf '# ever loading it with a PUF-wrapped black key. The PPK1/PPK2 and user-key\n'
        printf '# locks stay "-" so those slots remain available for later key rotation.\n'
        printf '#\n'
        printf '# WARNING: AES_KEY is the production red key, in the clear. This file is key\n'
        printf '# material - keep it in the key tree and back it up with the rest of it. Drop it\n'
        printf '# from the arm list only for a part that already holds this exact key: the\n'
        printf '# signed images are encrypted with keysrc = efuse_red_key and open with nothing\n'
        printf '# else.\n'
        printf '#\n'
        printf '# Injected by files/_sign_secure_boot.sh, which runs the package'"'"'s\n'
        printf '# common/fw-tool.py against mblp_prov/files/mblp-prov.elf.\n'

        printf '# --- key material (write-only in silicon; a read sees only the lock bits) ---\n'
        printf '%-17s = %s%s\n' AES_KEY "$AES_KEY" "$(note AES_KEY "$SECRET_KEY_FILE")"
        printf '%-17s = -\n' USER_KEY0
        printf '%-17s = -\n' USER_KEY1

        printf '# --- public key hashes (readable back) ---\n'
        printf '%-17s = %s%s\n' PPK0_HASH "$PPK0_HASH" "$(note PPK0_HASH "$PPK_HASH_FILE")"
        printf '%-17s = -\n' PPK1_HASH
        printf '%-17s = -\n' PPK2_HASH

        printf '# --- IVs (readable back; pinned by this flow, not chosen by bootgen) ---\n'
        printf '%-17s = %s%s\n' METAHEADER_IV "$METAHEADER_IV" "$(note METAHEADER_IV _efuse_iv.sh)"
        printf '%-17s = -\n' BLACK_IV
        printf '%-17s = %s%s\n' PLM_IV "$PLM_IV" "$(note PLM_IV _efuse_iv.sh)"
        printf '%-17s = -\n' DATA_PARTITION_IV

        printf '# --- revocation (readable back) ---\n'
        for i in 0 1 2 3 4 5 6 7; do printf '%-17s = -\n' "REVOKE_ID_${i}"; done

        # Spelled out rather than looped over one list, because the same eight names
        # split three ways here and a reader has to be able to see which is which.
        policy_why() {
            case "$1" in
                AES_WR_LK) printf 'no further AES key write' ;;
                PPK0_WR_LK) printf 'no further PPK0 hash write' ;;
                *) printf 'policy bit' ;;
            esac
        }
        # A refused fuse says so on its own line. "-" alone cannot tell "this flow does
        # not fill that slot" from "arming this ends the board", and this file is the
        # record an operator reads before an irreversible write.
        refused_why() {
            case "$1" in
                DEC_ONLY) printf 'S-HWRoT decrypts only with a PUF KEK; this flow is efuse_red_key' ;;
                AES_CRC_LK) printf 'the CRC check is the only proof the AES key burn landed' ;;
                *) printf 'this flow refuses it' ;;
            esac
        }
        policy_line() {
            if is_settable_policy "$1"; then
                printf '%-17s = %s%s\n' "$1" "$POLICY_ON" "$(note "$1" "$(policy_why "$1")")"
            elif is_refused_policy "$1"; then
                printf '%-17s = -   # REFUSED; %s\n' "$1" "$(refused_why "$1")"
            else
                printf '%-17s = -\n' "$1"
            fi
        }
        printf '# --- policy, burned after the values it depends on ---\n'
        policy_line DEC_ONLY

        printf '# --- locks, burned last. only an "armed" line is burned ---\n'
        for p in AES_WR_LK AES_CRC_LK USER_KEY0_WR_LK USER_KEY1_WR_LK \
            PPK0_WR_LK PPK1_WR_LK PPK2_WR_LK; do
            policy_line "$p"
        done
    } > "$TMP"

    mkdir -p "$(dirname "$OUT")" || sb_die "cannot create $(dirname "$OUT")"
    # 600 as the content lands, not after: the red key must not sit in a world-readable
    # file even for the moment between write and chmod.
    install -m 600 "$TMP" "$OUT" || sb_die "cannot write $OUT"

    echo "new  : $OUT"
    printf '  armed  : %s\n' "$ARMED"
    echo
    echo "RESULT: PASS - the key file describes this key set."
    sb_warn "it holds the red key in the clear; do not copy it out of the key tree"
}

usage() {
    cat << EOF
Usage: ./key_manager.sh --gen-keys <dir> [options]
       (runs files/_gen_keys.sh --keys <dir> [options])

Runs, in order:
  1. generate keys           the AES red key and the two RSA pairs
  2. derive PPK0 hash        bootgen -efuseppkbits, from the primary key
  3. eFUSE key file          every eFUSE field collected into one file

Creates, under $KEY_ROOT/:
  secret_key.txt   AES-256 red key. Key 0 of every .nky, and burned to eFUSE
  RSA/psk1_rsa.pem primary. Its PPK hash is what goes into eFUSE
  RSA/ssk1_rsa.pem secondary. Signs each partition
  ppk0_hash.txt    derived from the PSK. Public; the one auditable fuse
  efuse_keys.txt   every eFUSE field in one file - what the burn is done from

Options:
  --keys <dir>   where the key tree lives (default: $KEY_ROOT).
                 Give an absolute path outside this repo when signing from a
                 package: the package is replaced every build, the keys are not.
  --efuse-write "PPK0_HASH ..."
                 which fields efuse_keys.txt arms. Defaults to the blank-board
                 list:
                   AES_KEY PPK0_HASH METAHEADER_IV PLM_IV   the values
                   PPK0_WR_LK                               seal the PPK0 hash
                 Pass a shorter list for a board that already holds some of
                 those - arming a fuse that is already burned makes the write
                 fail whole, and nothing else gets burned either. Dropping
                 AES_KEY is only correct on a part that already holds it: the
                 signed images are encrypted with keysrc = efuse_red_key and
                 open with nothing else.
                 Two fuses a blank-board burn could also take are NOT in the
                 default:
                   AES_WR_LK  settable; sealing the AES row gives up ever
                              loading it with a PUF-wrapped black key. Add it
                              once a part's key burn is confirmed.
                   DEC_ONLY   REFUSED. S-HWRoT decrypts only with a PUF KEK and
                              every BIF here is efuse_red_key - it bricks the
                              part (0x308, then 0x30F). LP R.2, 2026-08-05.
                 AES_CRC_LK is refused too: it is the only proof an AES key burn
                 landed. PPK1/PPK2 and the user-key locks are left writable for
                 later key rotation, and a lock over a slot this flow does not
                 fill is refused rather than sealing it empty.
  -v, --verbose  stream each step's output instead of only PASS/FAIL
  -h, --help     this text

Keys are never overwritten: a file that exists is reported as 'keep :'. The PPK0
hash and the key file ARE rewritten every run - both are derived, and a stale
copy of an OTP value is the worst failure this flow has.

This is the whole of what the Key Manager does before signing; step 2 of the flow
builds the images.

The whole $KEY_ROOT/ tree is one backup unit - regenerating a single file
leaves it disagreeing with the rest. Full log under $LOG_ROOT/.
EOF
}

# VERBOSE below is consumed by files/_steplib.sh, which shellcheck cannot see
# from here because the source happens above this loop.
# shellcheck disable=SC2034
while [ $# -gt 0 ]; do
    case "$1" in
        --keys)
            KEY_ROOT=${2:?--keys needs a path}
            shift 2
            ;;
        --efuse-write)
            EFUSE_WRITE=${2:?--efuse-write needs a value}
            shift 2
            ;;
        -v | --verbose)
            VERBOSE=1
            shift
            ;;
        -h | --help)
            usage
            exit 0
            ;;
        *)
            echo "unknown option: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

# Absolute before anything reads it: the steps run from files/ and would count a
# relative path from there.
mkdir -p "$KEY_ROOT" 2> /dev/null || true
KEY_ROOT=$(readlink -f "$KEY_ROOT")
PSK=${KEY_ROOT}/RSA/psk1_rsa.pem
KEY_SHOW=$KEY_ROOT

sb_colors

# ------------------------------------------------------------------ preflight
sb_pf_init
sb_pf_tools openssl bootgen

# Complete or empty. A new PSK beside an old red key signs for a key no board was
# burned with, and nothing downstream can tell. Partial = report, operator decides.
KEY_FILES="secret_key.txt RSA/psk1_rsa.pem RSA/ssk1_rsa.pem"
n_have=0
n_want=0
SB_MISSING=
for f in $KEY_FILES; do
    n_want=$((n_want + 1))
    if [ -f "${KEY_ROOT}/${f}" ]; then
        n_have=$((n_have + 1))
    else
        SB_MISSING="${SB_MISSING} ${f}"
    fi
done

if [ "$n_have" -eq "$n_want" ]; then
    sb_pf_ok "complete key set in ${KEY_ROOT}"
    sb_pf_hint "it will be reused as it is; keys are never overwritten"
    sb_pf_hint "to make a DIFFERENT set, clear that directory first - see below"
elif [ "$n_have" -eq 0 ]; then
    sb_pf_ok "no key set in ${KEY_ROOT}: a new one will be created"
    sb_pf_hint "for a board family whose PPK0 hash is already burned, this is the"
    sb_pf_hint "wrong tree - a new key cannot sign for an old burn"
else
    sb_pf_bad "partial key set in ${KEY_ROOT}: ${n_have} of ${n_want} files present"
    for f in $SB_MISSING; do sb_pf_hint "missing: $f"; done
    sb_pf_hint ""
    sb_pf_hint "These three keys are one set. Generating the missing one now would"
    sb_pf_hint "pair a new key with the survivors, and an image signed by a set"
    sb_pf_hint "that never existed as a set boots on no board. Refusing."
    sb_pf_hint ""
    sb_pf_hint "If the missing file was deleted by mistake, restore it from the"
    sb_pf_hint "backup of that whole tree - it is one backup unit for this reason."
    sb_pf_hint "If you meant to start a new key set, move the old one aside first:"
    sb_pf_cmd "  " "mv ${KEY_ROOT} ${KEY_ROOT}.old && ./key_manager.sh --gen-keys ${KEY_ROOT}"
    sb_pf_hint "Never do that for a board family whose PPK0 hash is already burned."
fi

sb_pf_done

# ---------------------------------------------------------------------- steps
# Order is the dependency. STEPS/VERBOSE go to _steplib.sh - hence the disable.
# shellcheck disable=SC2034
STEPS=(
    "generate keys|sb_step_gen_keys|"
    "derive PPK0 hash|sb_step_ppk0_hash|"
    "eFUSE key file|sb_step_efuse_keyfile|"
)

# Through the environment rather than as arguments: both values can hold spaces or
# path separators, and _steplib.sh word-splits step arguments.
export SB_KEY_ROOT="$KEY_ROOT"
export SB_EFUSE_WRITE="$EFUSE_WRITE"

RUN_ID=$(date '+%Y%m%d-%H%M%S')
LOG_DIR="${LOG_ROOT}/${RUN_ID}-keys"
mkdir -p "$LOG_DIR"

printf '%s== key generation ==%s\n' "$C_BLD" "$C_OFF"
printf 'keys : %s\n' "$KEY_SHOW"
printf 'logs : %s/%s/\n\n' "$SCRIPT_DIR" "$LOG_DIR"

sb_run_steps
sb_summary || exit 1

# ---------------------------------------------------------------------- result
# Created or reused, in one line - not left to be inferred from the file list.
STEP_LOG="${LOG_DIR}/1-sb_step_gen_keys.log"
if grep -q '^new  :' "$STEP_LOG" 2> /dev/null; then
    printf '%sRESULT: PASS%s - a NEW key set was created.\n' "$C_GRN" "$C_OFF"
    CREATED=1
else
    printf '%sRESULT: PASS%s - the existing key set was left as it was.\n' "$C_GRN" "$C_OFF"
    CREATED=0
fi

# sha256 of the DER public PSK. Record it in the board-family register and compare
# before every signing run. Public data, unlike the tree it came from.
if [ -f "$PSK" ]; then
    FPR=$(openssl rsa -in "$PSK" -pubout -outform DER 2> /dev/null \
        | openssl sha256 -r 2> /dev/null | cut -d' ' -f1)
    printf '  psk_fpr : %s\n' "${FPR:-<could not read $PSK>}"
fi
printf '  keys    : %s\n' "$KEY_SHOW"

if [ "$CREATED" -eq 1 ]; then
    echo
    printf '%sBack up %s/ now, whole.%s A key set is only as good as its backup,\n' \
        "$C_YEL" "$KEY_SHOW" "$C_OFF"
    echo "and psk1_rsa.pem cannot be regenerated: lose it and every board burned"
    echo "with its PPK0 hash is permanently without a bootable image."
    echo "Record psk_fpr above in the board-family register before signing."
fi
